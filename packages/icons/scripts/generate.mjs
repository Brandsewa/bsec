// Regenerates src/generated/* from the pinned lucide-react devDependency (ISC licence, see LICENSE-LUCIDE).
// Run: pnpm --filter @bs/icons generate. Output is committed so builds never depend on this script.
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("lucide-react/package.json"));
const iconsDir = join(pkgDir, "dist", "esm", "icons");
const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });

const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAGS = new Set(["path", "circle", "rect", "line", "polyline", "polygon", "ellipse"]);
const ATTRS = new Set(["fill", "stroke", "stroke-width", "opacity", "d", "cx", "cy", "r", "x", "y", "x1", "y1", "x2", "y2", "rx", "ry", "width", "height", "points"]);

const icons = {};
for (const file of readdirSync(iconsDir).filter((f) => f.endsWith(".mjs")).sort()) {
  const name = file.slice(0, -4);
  if (!NAME.test(name)) continue;
  const mod = await import(pathToFileURL(join(iconsDir, file)).href);
  const data = mod.__iconData;
  // Aliases re-export another icon's data under a different file name: keep only the canonical one.
  if (!data || data.name !== name) continue;
  icons[name] = data.node.map(([tag, attrs]) => {
    if (!TAGS.has(tag)) throw new Error(`${name}: unexpected element <${tag}>`);
    const kept = {};
    for (const [k, v] of Object.entries(attrs)) {
      if (k === "key") continue;
      if (!ATTRS.has(k)) throw new Error(`${name}: unexpected attribute ${k}`);
      if (!/^[-A-Za-z0-9 .,#]*$/.test(String(v))) throw new Error(`${name}: unsafe value for ${k}`);
      kept[k] = String(v);
    }
    return [tag, kept];
  });
}
const names = Object.keys(icons).sort();
const header = "// GENERATED by scripts/generate.mjs from lucide-react. Do not edit.\n";
writeFileSync(join(out, "names.ts"), `${header}export const LUCIDE_NAMES: readonly string[] = ${JSON.stringify(names)};\n`);
writeFileSync(
  join(out, "data.ts"),
  `${header}export type IconNode = ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>;\n` +
    `export const LUCIDE_DATA: Readonly<Record<string, IconNode>> = ${JSON.stringify(icons)};\n`,
);
console.log(`wrote ${names.length} icons`);
